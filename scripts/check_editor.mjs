import assert from 'node:assert/strict';
import fs from 'node:fs';
import { request } from '../web/core.js';
const run = q => JSON.parse(request(JSON.stringify(q)));
const ok = q => { const r = run(q); assert.equal(r.ok, true, r.error); return r; };
const original = ok({ action: 'sample' });
const properties = { name: '可撤销的中文层', x: -11, y: 17, opacity: .6, visible: true, op: 'svg:screen' };
const edit = ok({ action: 'edit', path: [0, 0], ...properties });
assert.equal(edit.canUndo, true);
const preview = ok({ action: 'preview', path: [0, 0], x: 21, y: -9 });
assert.equal(Buffer.from(preview.rgba, 'base64').length, preview.width * preview.height * 4);
assert.notEqual(ok({action:'preview', path:[0,0], x:95, y:65}).rgba, preview.rgba);
// A preview cannot dirty the saved document or add an undo step.
const saved = ok({ action: 'export' }).data;
assert.equal(ok({ action: 'undo' }).png, original.png);
assert.equal(run({ action: 'undo' }).ok, false);
assert.equal(ok({ action: 'redo' }).png, edit.png);
assert.equal(ok({ action: 'export' }).data, saved);
assert.equal(run({ action: 'replace', path: [0, 0], data: 'bad' }).ok, false);
assert.equal(run({ action: 'open', data: 'bad' }).ok, false);
assert.equal(ok({ action: 'export' }).data, saved);
assert.equal(ok({ action: 'undo' }).png, original.png);
ok({ action: 'duplicate', path: [0, 0] });
assert.equal(run({ action: 'redo' }).ok, false);
const layer = ok({ action: 'layer-png', path: [0, 0] });
assert.ok(layer.data.length > 0);
let result = ok({ action: 'insert', parent: [0], index: 0, name: '导入图层', data: original.png });
assert.equal(result.tree[0].children[0].width, original.width);
result = ok({ action: 'replace', path: [0, 0], data: layer.data });
assert.equal(result.tree[0].children[0].width, 160);
result = ok({ action: 'group', parent: [], index: 0, name: '新组' });
assert.equal(result.tree[0].kind, 'group');
result = ok({ action: 'move', path: [1, 0], parent: [0] });
assert.equal(result.tree[0].children[0].name, '导入图层');
const beforeInvalidMove = ok({ action: 'export' }).data;
assert.equal(run({ action: 'move', path: [0], parent: [0] }).ok, false);
assert.equal(ok({ action: 'export' }).data, beforeInvalidMove);
// Destination indices must be adjusted if removal precedes the destination group.
result = ok({ action: 'move', path: [0], parent: [1] });
assert.equal(result.tree[0].children[0].name, '新组');
assert.ok(ok({ action: 'layers-zip' }).data.length > 0);
const reset = ok({ action: 'sample' });
assert.equal(reset.canUndo, false);
assert.equal(reset.canRedo, false);
const art = ok({ action: 'open', data: fs.readFileSync(new URL('../web/assets/capitole.ora', import.meta.url)).toString('base64') });
assert.equal(art.editable, true);
assert.equal(art.tree[0].children[0].visible, false);
const before = ok({ action: 'export' }).data;
const t0 = performance.now();
const realPreview = ok({ action: 'preview', path: [0, 1], x: 145, y: 115 });
console.log(`Real artwork preview (first, including cache): ${Math.round(performance.now() - t0)} ms, ${realPreview.width} × ${realPreview.height}`);
const t1 = performance.now();
ok({ action: 'preview', path: [0, 1], x: 147, y: 116 });
console.log(`Real artwork preview (cached): ${Math.round(performance.now() - t1)} ms`);
assert.equal(ok({ action: 'export' }).data, before);
ok({action:'duplicate',path:[0,3]});
assert.equal(ok({action:'undo'}).png, art.png);
assert.equal(ok({action:'export'}).data,before);
const exported = ok({ action: 'layers-zip' });
fs.mkdirSync(new URL('../_build/editor-test/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../_build/editor-test/layers.zip', import.meta.url), Buffer.from(exported.data, 'base64'));
console.log('PASS: transactional edits, undo/redo branching, noncommitting previews, insertion/replacement, duplicate, group moves and extraction');
